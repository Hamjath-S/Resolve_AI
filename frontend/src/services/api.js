/**
 * POST /tickets/{ticket_id}/resolve
 *
 * Called when the user confirms:
 *
 * "Yes, Issue Resolved"
 *
 * Backend changes the ticket to CLOSED.
 */

export async function resolveTicket(
  ticketId
) {

  if (!ticketId) {

    throw new ApiError(

      'Ticket ID is missing.',

      'validation'

    )

  }


  let response

  try {

    response = await fetch(

      `${API_BASE_URL}/tickets/${encodeURIComponent(ticketId)}/resolve`,

      {
        method: 'POST',

        headers: {
          'Content-Type':
            'application/json',
        },

        signal:
          AbortSignal.timeout(10000),

      }

    )

  } catch (err) {

    if (
      err.name === 'TimeoutError' ||
      err.name === 'AbortError'
    ) {

      throw new ApiError(

        'The backend did not respond while closing the ticket.',

        'network'

      )

    }

    throw new ApiError(

      'Could not reach the ResolveAI backend.',

      'backend_unavailable'

    )

  }


  if (!response.ok) {

    const message =
      await parseErrorBody(response)

    throw new ApiError(

      message,

      'api_error',

      response.status

    )

  }


  return response.json()

}


